export const EXERCISES = Object.freeze(
  definitions.map(([id, name, muscles, equipment, instructions]) =>
    Object.freeze({ id, name, muscles, equipment, instructions }),
  ),
);

export function prescribed(
  exerciseId,
  {
    sets = 3,
    reps = 10,
    weight = 0,
    restSeconds = 90,
    durationSeconds,
    group,
  } = {},
) {
  const exercise = EXERCISES.find((item) => item.id === exerciseId);
  if (!exercise) throw new Error(`Unknown catalog exercise: ${exerciseId}`);
  return {
    exerciseId,
    name: exercise.name,
    ...(group ? { group } : {}),
    sets: Array.from({ length: sets }, () => ({
      reps,
      weight,
      restSeconds,
      ...(durationSeconds ? { durationSeconds } : {}),
    })),
  };
}
